export const getDishById = (id: string): Dish | undefined => {
  return PHOBO_MENU.find((dish) => dish.id === id);
};

export const getDishesByCategory = (category: string): Dish[] => {
  if (category === 'all') return PHOBO_MENU;
  return PHOBO_MENU.filter((dish) => dish.category === category);
};

export const getBestsellers = (): Dish[] => {
  return PHOBO_MENU.filter((dish) => dish.tags.isBestseller);
};

export const getNewDishes = (): Dish[] => {
  return PHOBO_MENU.filter((dish) => dish.tags.isNew);
};

export const searchDishes = (query: string): Dish[] => {
  const lowerQuery = query.toLowerCase().trim();
  if (!lowerQuery) return PHOBO_MENU;

  return PHOBO_MENU.filter(
    (dish) =>
      dish.name.toLowerCase().includes(lowerQuery) ||
      dish.nameVietnamese.toLowerCase().includes(lowerQuery) ||
      dish.description.toLowerCase().includes(lowerQuery) ||
      dish.ingredients.some((ing) => ing.toLowerCase().includes(lowerQuery))
  );
};
